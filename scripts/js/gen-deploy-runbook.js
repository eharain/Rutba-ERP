#!/usr/bin/env node
'use strict';

/**
 * Generates the P3 deploy-box runbook (env prefixes, URL vars, systemd units).
 *
 *   node scripts/js/gen-deploy-runbook.js > docs/todo/erp2-program/03a-deploy-runbook.md
 *
 * The old→new mapping lives in p3-rename-map.js, which derives it rather than
 * tabulating it — see the note there on why. This file only formats.
 */

const {
  envPrefixRenames, urlVarRenames, unitRenames,
} = require('./p3-rename-map.js');

const envChanged = envPrefixRenames();
const urlChanged = urlVarRenames();
const unitChanged = unitRenames();

const L = [];
const p = (s = '') => L.push(s);

p('<!-- GENERATED by scripts/js/gen-deploy-runbook.js from config/apps.manifest.json.');
p('     Do not hand-edit — re-run the generator. -->');
p('<!-- verify-docs: runtime -->');
p('# P3 deploy-box runbook — env prefixes, URL vars and systemd units');
p();
p('The P3 restructure renamed workspaces, env prefixes, public URL variables and systemd units.');
p('The repo half is committed; **the boxes are not**. Until these steps run, a redeploy brings');
p('apps up with no env block — every `PREFIX__` lookup misses — and the renamed units do not exist.');
p();
p('Applies to the VPS (rutba.pk) and the LAN box (`rutba-nvr@192.168.0.46`). The LAN box keeps its');
p('master env **off-git**, so it cannot be replaced wholesale — it must be rewritten in place.');
p();
p('> Do the env half and the unit half in the **same window**. An app whose unit was renamed but');
p('> whose env was not will start and then fail every authenticated request.');
p();
p('## 0. Before starting Strapi — check the plugin links. Do not skip this.');
p();
p('On 2026-08-18 this exact restructure left `services/strapi`’s three `file:` dependencies');
p('installed as links pointing one directory too shallow. `npm` wrote them while the tree was');
p('mid-move; the `package.json` declarations were correct throughout. Strapi discovers plugins');
p('from `node_modules` and then **drops any table no loaded plugin claims** — so it booted');
p('without complaint and deleted all 13 `api_pro_*` tables plus `up_users_app_roles_lnk`.');
p();
p('The contract tables were rebuilt exactly by `seed:policy`. The **grants were not recoverable** —');
p('which user holds which role is data, and no descriptor knows it. Binary logging was on and');
p('still could not rebuild them.');
p();
p('So on each box, after pulling and installing, and **before the first `systemctl start`**:');
p();
p('```bash');
p('npm ci                      # or npm install — resolve the file: deps against the NEW paths');
p('npm run verify:wiring       # fails on any file: dep that resolves to a dangling link');
p('```');
p();
p('`verify:wiring` gained that check as a direct result. If it reports a DANGLING link, delete the');
p('link and reinstall — do not start Strapi first. And take a database dump before the first');
p('Strapi start regardless; it costs a minute and it is the only thing that would have saved the');
p('grants.');
p();
p('## 1. Env prefixes and URL variables');
p();
p(`${envChanged.length} env prefixes and ${urlChanged.length} URL variables changed. Do **not** hand-write seds for this —`);
p('run the tool, which is what the local machine was converted with:');
p();
p('```bash');
p('# dry run first — prints every key it would rename, exits 1 if any are pending');
p('node scripts/js/rename-env-prefixes.js .env.production');
p();
p('# apply (writes .env.production.bak alongside)');
p('node scripts/js/rename-env-prefixes.js .env.production --write');
p('```');
p();
p('It applies the renames longest-prefix-first, so `RUTBA_WEB__` cannot chew `RUTBA_WEB_USER__`,');
p('and it **refuses** any rename whose target key already exists rather than creating a duplicate');
p('— which matters for `NEXT_PUBLIC_CORE_URL` → `NEXT_PUBLIC_API_URL`, since strapi already owns');
p('`NEXT_PUBLIC_API_URL`. A refusal is printed, not silently skipped; resolve those two by hand.');
p();
p('Re-running on a converted file prints `already current` and exits 0, so it is safe in a deploy');
p('script and can gate the step.');
p();
p('<details><summary>The mapping it applies</summary>');
p();
p('| App | Old env prefix | New env prefix |');
p('|---|---|---|');
for (const r of envChanged) p(`| ${r.key} | \`${r.oldEnv}__\` | \`${r.newEnv}__\` |`);
p();
p('| App | Old URL var | New URL var |');
p('|---|---|---|');
for (const r of urlChanged) p(`| ${r.key} | \`${r.oldUrlVar}\` | \`${r.newUrlVar}\` |`);
p();
p('</details>');
p();
p(`## 2. systemd units — ${unitChanged.length} renamed`);
p();
if (!unitChanged.length) {
  p('None — every unit name survived.');
} else {
  p('Stop and disable the old unit **before** enabling the new one, or both bind the same port and');
  p('the second fails to start.');
  p();
  p('| App | Old unit | New unit | Port |');
  p('|---|---|---|---|');
  for (const r of unitChanged) {
    p(`| ${r.key} | \`${r.oldUnit}\` | \`${r.newUnit}\` | ${r.port ?? '—'} |`);
  }
  p();
  p('```bash');
  for (const r of unitChanged) p(`sudo systemctl disable --now ${r.oldUnit}`);
  p('sudo systemctl daemon-reload');
  for (const r of unitChanged) p(`sudo systemctl enable --now ${r.newUnit}`);
  p('```');
}
p();
p('## 3. Verify');
p();
p('```bash');
p('node scripts/js/rename-env-prefixes.js .env.production   # must print "already current"');
p('systemctl list-units "rutba_*" --no-pager                # all NEW names, all active');
p('curl -sf localhost:4020/_health || echo FAIL             # core answers');
p('```');
p();
p('An app that starts but 500s on every authenticated route almost always means its env block did');
p('not resolve — check that its `PREFIX__PORT` uses the new prefix.');
p();

console.log(L.join('\n'));
