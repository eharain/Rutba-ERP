#!/usr/bin/env node
'use strict';

/**
 * Generates the P3 deploy-box runbook (env prefixes + systemd units) from
 * config/apps.manifest.json.
 *
 *   node scripts/js/gen-deploy-runbook.js > docs/todo/erp2-program/03a-deploy-runbook.md
 *
 * ── Why the old names are derived, not tabulated ────────────────────────────
 *
 * The NEW identity comes from the manifest. The OLD identity no longer exists
 * anywhere in the tree, so it has to come from somewhere else — and a
 * hand-written mapping table is exactly what corrupted migration 022 during
 * this restructure (§8 finding 3). The first draft of this generator repeated
 * the mistake: it tabulated the old units by hand and got four of them wrong
 * (`rutba_sale` for what is really `rutba_pos_sale`, and the same for auth,
 * stock and strapi).
 *
 * So only the old DIRECTORY names are listed, and they are verifiable in one
 * command against the commit before the move:
 *
 *   git ls-tree --name-only -d 1684f226~1
 *
 * Everything else follows the two rules that were in force at the time:
 *   env prefix = DIR upper-cased, '-' → '_'          (env-utils.js, pre-fix)
 *   unit name  = dir with '-' → '_', prefixed with
 *                'rutba_' unless it already starts with it
 *
 * Both rules are asserted against the recorded unit list below before anything
 * is emitted, so a wrong rule fails loudly instead of printing a bad runbook.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');

/** Top-level workspace dirs at 1684f226~1 (the commit before the move). */
const OLD_DIR = {
  strapi: 'pos-strapi', core: 'rutba-core',
  pos: 'pos-sale', stock: 'pos-stock', auth: 'pos-auth',
  storefront: 'rutba-web', portal: 'rutba-web-user',
  orders: 'rutba-order-management', control: 'rutba-inventory',
  console: 'rutba-admin', crm: 'rutba-crm', rider: 'rutba-rider',
  marketplace: 'rutba-marketplace', helpdesk: 'rutba-helpdesk',
  manufacturing: 'rutba-manufacturing', hr: 'rutba-hr', ess: 'rutba-ess',
  accounts: 'rutba-accounts', payroll: 'rutba-payroll', cms: 'rutba-cms',
  social: 'rutba-social', campaigns: 'rutba-campaigns', mail: 'rutba-mail',
  seed: 'rutba-seed',
};

/** Unit names as they appear in scripts/rutba_apps.sh at 1684f226~1. */
const RECORDED_OLD_UNITS = new Set([
  'rutba_accounts', 'rutba_admin', 'rutba_campaigns', 'rutba_cms', 'rutba_core',
  'rutba_crm', 'rutba_ess', 'rutba_helpdesk', 'rutba_hr', 'rutba_inventory',
  'rutba_mail', 'rutba_manufacturing', 'rutba_marketplace', 'rutba_order_management',
  'rutba_payroll', 'rutba_pos_auth', 'rutba_pos_sale', 'rutba_pos_stock',
  'rutba_pos_strapi', 'rutba_rider', 'rutba_seed', 'rutba_social', 'rutba_web',
  'rutba_web_user',
]);

const oldEnvOf = (dir) => dir.toUpperCase().replace(/-/g, '_');
const oldUnitOf = (dir) => {
  const u = dir.replace(/-/g, '_');
  return u.startsWith('rutba_') ? u : `rutba_${u}`;
};

// Fail loudly if a derivation rule has drifted from what was recorded.
const derived = new Set(Object.values(OLD_DIR).map(oldUnitOf));
const missing = [...RECORDED_OLD_UNITS].filter((u) => !derived.has(u));
const extra = [...derived].filter((u) => !RECORDED_OLD_UNITS.has(u));
if (missing.length || extra.length) {
  console.error('[gen-deploy-runbook] old-unit derivation does not match the recorded list.');
  if (missing.length) console.error(`  recorded but not derived: ${missing.join(', ')}`);
  if (extra.length) console.error(`  derived but not recorded:  ${extra.join(', ')}`);
  process.exit(1);
}

const manifest = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'config', 'apps.manifest.json'), 'utf8')
);
const svcs = (manifest.services || []).filter((s) => OLD_DIR[s.key]);
const envChanged = svcs
  .filter((s) => oldEnvOf(OLD_DIR[s.key]) !== s.envPrefix)
  .sort((a, b) => oldEnvOf(OLD_DIR[b.key]).length - oldEnvOf(OLD_DIR[a.key]).length);
const unitChanged = svcs.filter((s) => oldUnitOf(OLD_DIR[s.key]) !== s.unit);

const L = [];
const p = (s = '') => L.push(s);

p('<!-- GENERATED by scripts/js/gen-deploy-runbook.js from config/apps.manifest.json.');
p('     Do not hand-edit — re-run the generator. -->');
p('<!-- verify-docs: runtime -->');
p('# P3 deploy-box runbook — env prefixes and systemd units');
p();
p('The P3 restructure renamed workspaces, env prefixes and systemd units. The repo half is');
p('committed; **the boxes are not**. Until these steps run, a redeploy brings apps up with no env');
p('block — every `PREFIX__` lookup misses — and the renamed units do not exist.');
p();
p('Applies to the VPS (rutba.pk) and the LAN box (`rutba-nvr@192.168.0.46`). The LAN box keeps its');
p('master env **off-git**, so it must be edited in place; nothing in this repo will update it.');
p();
p('> Do the env half and the unit half in the **same window**. An app whose unit was renamed but');
p('> whose env was not will start and then fail every authenticated request.');
p();
p(`## 1. Env prefixes — ${envChanged.length} changed`);
p();
p('`OLD__VAR` becomes `NEW__VAR`; the part after `__` is untouched. Applied longest-prefix-first so');
p('`RUTBA_WEB__` cannot chew `RUTBA_WEB_USER__`.');
p();
p('| App | Old prefix | New prefix |');
p('|---|---|---|');
for (const s of envChanged) p(`| ${s.key} | \`${oldEnvOf(OLD_DIR[s.key])}__\` | \`${s.envPrefix}__\` |`);
p();
p('```bash');
p('cp .env.production .env.production.bak.$(date +%Y%m%d%H%M%S)   # this edits in place');
for (const s of envChanged) {
  p(`sed -i 's/^${oldEnvOf(OLD_DIR[s.key])}__/${s.envPrefix}__/' .env.production`);
}
p('```');
p();
p('Verify — must print nothing:');
p();
p('```bash');
p(`grep -oE '^(${envChanged.map((s) => oldEnvOf(OLD_DIR[s.key])).join('|')})__' .env.production`);
p('```');
p();
p(`## 2. systemd units — ${unitChanged.length} renamed`);
p();
if (!unitChanged.length) {
  p('None — every unit name survived.');
} else {
  p('Stop and disable the old unit **before** enabling the new one, or both bind the same port and');
  p('the second fails to start.');
  p();
  p('| App | Old unit | New unit | Port |');
  p('|---|---|---|---|');
  for (const s of unitChanged) {
    p(`| ${s.key} | \`${oldUnitOf(OLD_DIR[s.key])}\` | \`${s.unit}\` | ${s.port ?? '—'} |`);
  }
  p();
  p('```bash');
  for (const s of unitChanged) p(`sudo systemctl disable --now ${oldUnitOf(OLD_DIR[s.key])}`);
  p('sudo systemctl daemon-reload');
  for (const s of unitChanged) p(`sudo systemctl enable --now ${s.unit}`);
  p('```');
}
p();
p('## 3. Verify');
p();
p('```bash');
p('systemctl list-units "rutba_*" --no-pager        # all NEW names, all active');
p('curl -sf localhost:4020/api/health || echo FAIL  # core answers');
p('```');
p();
p('An app that starts but 500s on every authenticated route almost always means its env block did');
p('not resolve — check that its `PREFIX__PORT` uses the new prefix.');
p();

console.log(L.join('\n'));
